// Regenerates TypeScript types from the frozen JSON Schema files under schemas/.
//
// Selection rationale (documented in docs/plans/studio_roadmap_01/30_PLAN_C_API_UI_INTEGRATION.md
// and C0 evidence): Plan A/B publish JSON Schema artifacts (studio.artifact/v1alpha1), so the
// generation path is JSON Schema -> TypeScript via json-schema-to-typescript. Generated output is
// committed; check-drift.mjs proves it stays in sync with the schemas.
import { compile } from "json-schema-to-typescript";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const schemasDir = path.join(here, "..", "schemas");
const outDir = process.env.OVERRIDE_GENERATED_DIR || path.join(here, "..", "src", "generated");

const BANNER = "/* Generated by json-schema-to-typescript from schemas/. Do not edit by hand. Run `npm run generate:contracts`. */";

const toPascalCase = (name) =>
  name
    .split(/[-.]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

const files = (await readdir(schemasDir)).filter((f) => f.endsWith(".schema.json"));
await mkdir(outDir, { recursive: true });

const indexLines = [];
for (const file of files.sort()) {
  const schemaPath = path.join(schemasDir, file);
  const schema = JSON.parse(await readFile(schemaPath, "utf8"));
  const baseName = file.replace(/\.schema\.json$/, "");
  const typeName = toPascalCase(baseName);
  const ts = await compile(schema, typeName, {
    cwd: schemasDir,
    bannerComment: BANNER,
    additionalProperties: false,
  });
  await writeFile(path.join(outDir, `${baseName}.ts`), ts, "utf8");
  indexLines.push(`export * from './${baseName}';`);
}
await writeFile(path.join(outDir, "index.ts"), indexLines.join("\n") + "\n", "utf8");

console.log(`Regenerated ${files.length} contract type files into src/generated/`);
